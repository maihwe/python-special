# Topic 2: Variables - Examples

# Example 1: Create and use a variable
age = 25
print("Age:", age)

# Example 2: Multiple variables
midterm = 85
final = 92
project = 88
print("Scores:", midterm, final, project)

# Example 3: Calculate with variables
midterm = 85
final = 92
project = 88
average = (midterm + final + project) / 3
print("Average:", average)

# Example 4: Changing a variable
score = 85
print("Initial score:", score)
score = 90
print("Updated score:", score)

# Example 5: Use variable in calculation
x = 5
y = 3
print("Sum:", x + y)
print("Product:", x * y)

# Example 6: String variables
first_name = "Alice"
last_name = "Johnson"
print("Name:", first_name, last_name)

# Example 7: Boolean variables
is_student = True
is_employed = False
print("Student:", is_student)
print("Employed:", is_employed)

# Example 8: Mixed types
name = "Bob"
age = 30
gpa = 3.8
print("Name:", name)
print("Age:", age)
print("GPA:", gpa)

# Example 9: Reuse values
price = 19.99
quantity = 5
total = price * quantity
print("Price:", price)
print("Quantity:", quantity)
print("Total:", total)

# Example 10: Updating based on previous value
balance = 1000
withdrawal = 250
balance = balance - withdrawal
print("New balance:", balance)

# Example 11: Calculate percentage
score = 85
total = 100
percentage = (score / total) * 100
print("Percentage:", percentage)

# Example 12: Distance calculation
length = 10
width = 5
area = length * width
print("Area:", area)

# Example 13: Temperature conversion
celsius = 25
fahrenheit = (celsius * 9/5) + 32
print("Celsius:", celsius)
print("Fahrenheit:", fahrenheit)

# Example 14: Years calculation
birth_year = 2000
current_year = 2026
age = current_year - birth_year
print("Age:", age)

# Example 15: Grade calculation
test1 = 85
test2 = 92
test3 = 88
average = (test1 + test2 + test3) / 3
print("Average:", average)

