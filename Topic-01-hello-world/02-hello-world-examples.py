# Topic 1: Hello World - Examples

# Example 1: Basic output
print("Hello, World!")

# Example 2: Display a message
print("Welcome to Python!")

# Example 3: Using single quotes
print('Single quotes work too')

# Example 4: Multiple prints
print("First line")
print("Second line")
print("Third line")

# Example 5: Blank line
print("Line 1")
print()
print("Line 3")

# Example 6: Using newline character
print("Line 1\nLine 2\nLine 3")

# Example 7: Using tabs
print("Name\tAge")
print("Alice\t25")

# Example 8: Numbers in print
print(42)
print(3.14)

# Example 9: Text with quotes
print('He said "Hello"')
print("It's a nice day")

# Example 10: Long text
print("This is a very long string that goes on and on and on")

# Example 11: Print with multiple items
print("The answer is", 42)

# Example 12: Empty print
print("Start")
print()
print("End")

# Example 13: Escape characters
print("Backslash: \\")
print("Tab:\there")

# Example 14: Real-world example
print("=== Welcome ===")
print("Name: Alice")
print("Score: 95")
print("Status: Passed")

# Example 15: Mixed numbers and text
print("You scored", 95, "out of 100")

